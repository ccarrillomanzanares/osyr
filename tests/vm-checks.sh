#!/bin/sh
# OSYR — checks inside the image (run by tests/run.py over the serial
# console, as the osyr user). Each one prints "PASS name" or
# "FAIL name: detail". All test data goes to /run or /tmp: the VM boots in
# snapshot mode and nothing is left when it shuts down.
# Variables: HOST (the VPS as seen from QEMU), GITPORT, MOCKPORT, PW (password).
HOST=${HOST:-10.0.2.2}; PW=${PW:-osyr}
S() { echo "$PW" | sudo -S -p "" "$@"; }
pass() { echo "PASS $1"; }
fail() { echo "FAIL $1: $2"; }
check() { # check <name> <command...>: PASS if the command exits with 0
    n="$1"; shift
    if out=$("$@" 2>&1); then pass "$n"; else fail "$n" "$(echo "$out" | tail -2 | tr '\n' ' ')"; fi
}
wj() { python3 -c 'import json,sys; d=json.loads(sys.stdin.read().strip().splitlines()[-1]); print(eval(sys.argv[1]))' "$1"; }
jcode() { python3 -c 'import json,sys; print(json.loads(sys.stdin.read().strip().splitlines()[-1]).get("code"))'; }

# Without KVM the VM is slow: swayidle would lock the session after 5 min and sway
# does not allow capturing a locked screen. Paused during the checks.
pkill -STOP -x swayidle

# --- System ---------------------------------------------------------------------
# No dependency cycles at boot: systemd breaks them by dropping jobs
# (with osyr-zram badly ordered, the /tmp mount was lost)
cyc=$(journalctl -b --no-pager | grep -c 'ordering cycle')
[ "$cyc" = 0 ] && [ "$(findmnt -n -o FSTYPE /tmp)" = tmpfs ] && pass boot-no-cycles || \
    fail boot-no-cycles "$cyc cycle(s); /tmp is $(findmnt -n -o FSTYPE /tmp)"
[ -z "$(systemctl --failed --no-legend)" ] && pass services-ok || fail services-ok "$(systemctl --failed --no-legend | tr '\n' ' ')"
[ "$(systemctl is-active sshd)" != active ] && pass sshd-off || fail sshd-off "sshd is running"
# Firewall: table loaded and input closed by default (output is tested by
# every check that downloads something from the VPS)
fw=$(S nft list chain inet osyr input 2>&1)
echo "$fw" | grep -q 'policy drop' && pass firewall-on || fail firewall-on "$(systemctl is-active osyr-firewall) $(echo "$fw" | head -2 | tr '\n' ' ')"
S systemctl reload osyr-firewall && [ "$(S nft list tables | grep -c 'inet osyr')" = 1 ] && pass firewall-reload || fail firewall-reload "reload failed or duplicated table"
open=$(ss -ltnuH 2>/dev/null | awk '{print $5}' | grep -vE '^(127\.|\[::1\]|.*%lo:|10\.0\.2\.15%.*:68$)' | tr '\n' ' ')
[ -z "$open" ] && pass no-open-ports || fail no-open-ports "$open"
grep -q '^COMMIT=' /etc/osyr/build-info && pass build-info || fail build-info "missing"
# (BusyBox's passwd has no -S: the status is read from /etc/shadow)
[ -n "$(S grep '^root:' /etc/shadow | cut -d: -f2)" ] && pass root-status || fail root-status "no root entry in shadow"
command -v chpasswd >/dev/null && pass chpasswd-present || fail chpasswd-present "osyr-firstboot needs it"
# Not in the input group (raw keyboard); suspend without a password only with that command
! id -nG | grep -qw input && pass no-input-group || fail no-input-group "$(id -nG)"
# (only that command without a password: poweroff still asks for it via wheel)
nopw=$(sudo -n -l 2>/dev/null | grep -o 'NOPASSWD: .*')
echo "$nopw" | grep -qx 'NOPASSWD: /usr/bin/systemctl suspend' && ! echo "$nopw" | grep -q 'systemctl \*\|ALL$\|poweroff' \
    && pass suspend-allowed || fail suspend-allowed "$(sudo -n -l 2>&1 | tail -3 | tr '\n' ' ')"
[ "$(stat -c '%a %U:%G' /etc/osyr/diag.token)" = "640 root:osyr" ] && pass diag-token-private || fail diag-token-private "$(stat -c '%a %U:%G' /etc/osyr/diag.token)"
# The VM has a serial port (type 16550A): osyr-uart.conf's condition must keep its getty
[ "$(systemctl is-active serial-getty@ttyS0)" = active ] && pass serial-getty || fail serial-getty "$(systemctl is-active serial-getty@ttyS0)"
# Stable history for the prompt cache (template generated by osyr-llama)
llargs=$(tr '\0' ' ' < /proc/$(pidof llama-server | cut -d' ' -f1)/cmdline 2>/dev/null)
echo "$llargs" | grep -q -- '--chat-template-file' && pass llama-stable-template || \
    fail llama-stable-template "$(echo "$llargs" | cut -c1-200)"
# On-demand vision: the agent without the projector and the vision socket listening
echo "$llargs" | grep -q -- '--mmproj' && fail llama-no-mmproj "$(echo "$llargs" | cut -c1-200)" || pass llama-no-mmproj
[ "$(systemctl is-active osyr-llama-vision-proxy.socket)" = active ] && pass vision-socket || \
    fail vision-socket "$(systemctl is-active osyr-llama-vision-proxy.socket)"
# Emoji in colour: the terminal's font falls back to Noto Color Emoji (not boxes,
# not DejaVu Sans's black-and-white ones)
fb=$(fc-match -s "DejaVu Sans Mono" family | awk '!s[$0]++' | sed -n 2p)
[ "$fb" = "Noto Color Emoji" ] && fc-list ':charset=1f680' family | grep -q 'Noto Color Emoji' \
    && pass emoji-font || fail emoji-font "fallback: $fb"

# --- Network ---------------------------------------------------------------------
check net-status osyr net status
[ "$(osyr net status --json | jcode)" = OK ] && pass net-json || fail net-json "not OK"

# Wifi with virtual radios: wlan1 access point with DHCP, wlan0 station
S modprobe mac80211_hwsim radios=2 && sleep 4
printf '[Match]\nName=wlan1\n[Network]\nAddress=192.168.80.1/24\nDHCPServer=yes\n' > /tmp/ap.network
S mkdir -p /run/systemd/network && S cp /tmp/ap.network /run/systemd/network/10-osyr-test-ap.network
S networkctl reload; iwctl device wlan1 set-property Mode ap; sleep 2
# The test access point's DHCP server is on this same VM: the
# firewall (client only) would block its requests. Opened only on wlan1.
S nft add rule inet osyr input iifname wlan1 udp dport 67 accept
iwctl ap wlan1 start OSYR-TEST testpass123; sleep 2; S networkctl reconfigure wlan1; sleep 3
osyr net wifi scan | grep -q OSYR-TEST && pass wifi-scan || fail wifi-scan "OSYR-TEST not found"
[ "$(osyr net wifi connect OSYR-TEST --json | jcode)" = WIFI_NEEDS_PASSWORD ] && pass wifi-needs-password || fail wifi-needs-password "?"
# Approximate name (as the model or voice writes it): finds OSYR-TEST
[ "$(osyr net wifi connect "osyr test" --json | jcode)" = WIFI_NEEDS_PASSWORD ] && pass wifi-fuzzy-ssid || fail wifi-fuzzy-ssid "?"
# The password via stdin (used by the chat and the first boot) and to iwctl at its prompt:
# no process carries it on the command line while connecting
pwwatch() { ( end=$(($(date +%s)+60)); while [ "$(date +%s)" -lt $end ]; do
    for f in /proc/[0-9]*/cmdline; do tr '\0' ' ' < "$f" 2>/dev/null; echo; done | grep -E "$1" | grep -v grep >> /tmp/pwleak
    done ) & W=$!; }
pwwatch 'wrongpass1|testpass123'
[ "$(echo wrongpass1 | osyr net wifi connect OSYR-TEST --password-stdin --json | jcode)" = WIFI_AUTH_FAILED ] && pass wifi-bad-password || fail wifi-bad-password "?"
[ "$(echo short | osyr net wifi connect OSYR-TEST --password-stdin --json | jcode)" = WIFI_AUTH_FAILED ] && pass wifi-short-password || fail wifi-short-password "?"
S ls /var/lib/iwd | grep -q OSYR-TEST && fail wifi-no-residue "profile saved after failure" || pass wifi-no-residue
r=$(echo testpass123 | osyr net wifi connect OSYR-TEST --password-stdin --json); [ "$(echo "$r" | jcode)" = OK ] && pass wifi-connect || fail wifi-connect "$r"
kill $W 2>/dev/null
[ ! -s /tmp/pwleak ] && pass wifi-password-not-in-argv || fail wifi-password-not-in-argv "$(sort -u /tmp/pwleak | head -2 | tr '\n' ' ')"
python3 -c "import runpy; print(runpy.run_path('/usr/bin/osyr-status')['line']())" | grep -q "WIFI OSYR-TEST" && pass bar-wifi || fail bar-wifi "bar"
# The agent connects: the password is typed without echo (first wrong, then right) and the
# model does not see it. The network is forgotten so that it asks for it.
iwctl station wlan0 disconnect; iwctl known-networks OSYR-TEST forget
cat > /tmp/wifi-drive.py <<'PYEOF'
import os, pty, re, sys, time
pid, fd = pty.fork()
if pid == 0:
    os.execvp("python3", ["python3", "-c", "import importlib.machinery as M, importlib.util as U, json\n"
        "l=M.SourceFileLoader('c','/usr/bin/osyr-chat'); m=U.module_from_spec(U.spec_from_loader('c',l)); l.exec_module(m)\n"
        "print('RESULT', json.dumps(m.run_osyr('net wifi connect \"osyr test\" --password frommodel')))"])
out = b""
def wait(pat, t=180):
    global out
    end = time.time() + t
    while time.time() < end:
        try:
            out += os.read(fd, 4096)
        except OSError:
            break
        if re.search(pat, out):
            return
    print("TIMEOUT", pat, out.decode(errors="replace")[-300:]); sys.exit(1)
wait(rb'Password for wifi "OSYR-TEST"'); os.write(fd, b"wrongpass1\n")
wait(rb'Wrong password\. Password for wifi'); os.write(fd, b"testpass123\n")
wait(rb"RESULT .*\n")
text = out.decode(errors="replace")
print("SHOWN" if "testpass123" in text or "wrongpass1" in text else "HIDDEN")
print(text[text.index("RESULT"):].splitlines()[0])
PYEOF
r=$(python3 /tmp/wifi-drive.py 2>&1)
echo "$r" | grep -q HIDDEN && echo "$r" | grep -q '"code": "OK"' && pass agent-wifi-password || fail agent-wifi-password "$(echo "$r" | tail -2 | tr '\n' ' ')"
check wifi-disconnect osyr net wifi disconnect

# --- Sound -------------------------------------------------------------------------
for u in pipewire pipewire-pulse wireplumber; do
    [ "$(systemctl --user is-active $u)" = active ] && pass "audio-$u" || fail "audio-$u" "$(systemctl --user is-active $u)"
done
# User services only: the system ones opened the card and left no microphone (HP 15s)
sysaudio=$(systemctl list-units --no-legend --plain 'pipewire*' 'wireplumber*' | awk '{print $1}' | tr '\n' ' ')
[ -z "$sysaudio" ] && pass audio-no-system-pipewire || fail audio-no-system-pipewire "$sysaudio"
[ -f /usr/lib/spa-0.2/bluez5/libspa-bluez5.so ] && pass audio-bluetooth-plugin || fail audio-bluetooth-plugin "PipeWire built without bluez5"
check audio-status osyr audio status
check audio-volume osyr audio volume 60
pactl info 2>/dev/null | grep -q "on PipeWire" && pass audio-pulse-apps || fail audio-pulse-apps "pactl does not see PipeWire"
python3 - <<'EOF'
import math, struct, wave
with wave.open("/tmp/tone.wav", "wb") as w:
    w.setnchannels(1); w.setsampwidth(2); w.setframerate(48000)
    w.writeframes(b"".join(struct.pack("<h", int(12000 * math.sin(2 * math.pi * 440 * i / 48000))) for i in range(48000)))
EOF
check audio-alsa-apps aplay -q -D default /tmp/tone.wav
check audio-test osyr audio test "sound test"
echo "hola" | espeak -v es --stdout | pw-play - && pass voice-speaks || fail voice-speaks "espeak | pw-play -"
check audio-mute osyr audio mute on
osyr audio status --json | grep -q '"muted": true' && pass audio-muted || fail audio-muted "not muted"
osyr audio mute off >/dev/null
[ -x /opt/whisper/bin/whisper-cli ] && ls /usr/share/osyr/models/whisper/*.bin >/dev/null 2>&1 && pass voice-installed || fail voice-installed "whisper or model missing"
# The image's real whisper (its own ggml, not llama.cpp's): one second of audio
python3 -c "import wave; w=wave.open('/tmp/s.wav','wb'); w.setnchannels(1); w.setsampwidth(2); w.setframerate(16000); w.writeframes(bytes(32000))"
out=$(timeout 900 /opt/whisper/bin/whisper-cli -m /usr/share/osyr/models/whisper/*.bin -f /tmp/s.wav -l es -nt -np -t 4 2>&1); rc=$?
[ $rc -eq 0 ] && ! echo "$out" | grep -q GGML_ASSERT && pass voice-whisper-runs || fail voice-whisper-runs "rc=$rc $(echo "$out" | grep -m1 -E 'ASSERT|error')"
ls /lib/firmware/intel/sof/sof-icl.ri >/dev/null 2>&1 && ls /usr/share/alsa/ucm2 >/dev/null 2>&1 && pass audio-sof-ucm || fail audio-sof-ucm "SOF or UCM missing"

# --- Help (Super+F1): the same as https://ccmai.org/osyr/help.html ---------------
osyr-help --plain 2>&1 | grep -q "Keyboard shortcuts" && grep -q 'mod+F1 exec.*osyr-help' /etc/sway/config && \
    pass help || fail help "$(osyr-help --plain 2>&1 | head -2)"

# --- Screen and diagnostics -----------------------------------------------------------
# The VM is slow: swayidle will have turned the screen off and grim would have nothing to copy
SWAYSOCK=$(ls /run/user/$(id -u)/sway-ipc.*.sock 2>/dev/null | head -1) swaymsg 'output * power on' >/dev/null
sleep 3  # until sway draws a frame, grim fails ("failed to copy output")
f=$(osyr-screenshot) && [ -s "$f" ] && pass screenshot || fail screenshot "$f locked=$(pgrep -x swaylock >/dev/null && echo yes || echo no)"
# Without a terminal to ask, screenshots are not included; with --screenshots, they are
osyr-diag --local --quick > /tmp/diag0.out 2>&1
t0=$(sed -n 's/.*saved \(\/tmp\/[^ ]*\.tar\.gz\).*/\1/p' /tmp/diag0.out)
[ -n "$t0" ] && ! gzip -dc "$t0" | tar -tf - | grep -q 'screenshots/' && pass diag-no-screenshots-by-default || \
    fail diag-no-screenshots-by-default "$(tail -2 /tmp/diag0.out)"
sleep 1  # another bundle name (it includes the time with seconds)
osyr-diag --local --screenshots > /tmp/diag.out 2>&1
t=$(sed -n 's/.*saved \(\/tmp\/[^ ]*\.tar\.gz\).*/\1/p' /tmp/diag.out)
[ -n "$t" ] && gzip -dc "$t" | tar -tf - | grep -q 'screenshots/osyr-' && pass diag-screenshots || fail diag-screenshots "$(tail -2 /tmp/diag.out)"
gzip -dc "$t" | tar -tf - | grep -q 'audio.txt' && pass diag-audio || fail diag-audio "no audio.txt"

# --- Desktop: lock, notifications, displays -------------------------------------------
export WAYLAND_DISPLAY=${WAYLAND_DISPLAY:-wayland-1}
for p in swayidle mako; do pgrep -x $p >/dev/null && pass "desktop-$p" || fail "desktop-$p" "not running"; done
command -v swaylock >/dev/null && pass desktop-swaylock || fail desktop-swaylock "missing"
# swaylock checks the password with PAM as osyr, that is, with unix_chkpwd:
# without setuid it rejected all of them and the lock could not be removed
printf '%s\0' "$PW" | /usr/sbin/unix_chkpwd osyr nullok && pass lock-password-ok || \
    fail lock-password-ok "$(ls -l /usr/sbin/unix_chkpwd)"
printf '%s\0' "not-$PW" | /usr/sbin/unix_chkpwd osyr nullok 2>/dev/null && \
    fail lock-password-wrong "accepted a wrong password" || pass lock-password-wrong
python3 -c "import sys; sys.path.insert(0,'/usr/lib/osyr'); from osyr import notify; sys.exit(0 if notify.send('OSYR test', 'notification') else 1)" \
    && pass notify-send || fail notify-send "mako did not take it"
n=$(osyr ui display list --json | python3 -c 'import json,sys; print(len(json.loads(sys.stdin.read().strip().splitlines()[-1])["data"]["displays"]))')
[ "${n:-0}" -ge 1 ] && pass display-list || fail display-list "no displays"
if [ "${n:-0}" -ge 2 ]; then
    check display-extend osyr ui display extend right
    osyr ui display list --json | grep -q '"position": \[[1-9]' && pass display-extended || fail display-extended "second display not placed to the right"
    check display-mirror osyr ui display mirror
    sleep 3; pgrep -x wl-mirror >/dev/null && pass display-mirror-running || fail display-mirror-running "wl-mirror not running"
    check display-unmirror osyr ui display extend
    second=$(osyr ui display list --json | python3 -c 'import json,sys; print(json.loads(sys.stdin.read().strip().splitlines()[-1])["data"]["displays"][1]["name"])')
    check display-off osyr ui display off "$second"
    first=$(osyr ui display list --json | python3 -c 'import json,sys; print(json.loads(sys.stdin.read().strip().splitlines()[-1])["data"]["displays"][0]["name"])')
    [ "$(osyr ui display off "$first" --json | jcode)" = UI_LAST_DISPLAY ] && pass display-keeps-last || fail display-keeps-last "turned off the last display"
    check display-on osyr ui display on "$second"
    ls ~/.config/sway/config.d/50-osyr-displays.conf >/dev/null && pass display-remembered || fail display-remembered "no config saved"
fi

# --- Bluetooth (the VM has no adapter: it must say so, not fail) -----------------------
{ [ "$(systemctl is-active bluetooth)" = active ] || [ ! -d /sys/class/bluetooth ]; } && pass bt-service || fail bt-service "$(systemctl is-active bluetooth)"
