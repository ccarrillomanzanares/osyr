# --- Hardware self-test ----------------------------------------------------------------
osyr sys selftest --json > /tmp/selftest.json 2>&1
python3 - <<'PY' && pass selftest-runs || fail selftest-runs "$(tail -c 200 /tmp/selftest.json)"
import json
r = json.loads(open("/tmp/selftest.json").read().strip().splitlines()[-1])
